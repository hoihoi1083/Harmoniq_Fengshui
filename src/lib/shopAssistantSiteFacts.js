/**
 * 購物助理用的站內事實（與訂單頁、報告預覽頁、messages 條款／退換貨文案對齊）。
 * 僅使用「連結文字 + Markdown」，避免模型複製反引號路徑或 [訂單編號] 等佔位。
 */
export function getShopAssistantSiteFacts(locale) {
	const L = locale === "zh-CN" ? "zh-CN" : "zh-TW";
	const base = `/${L}`;
	const isCn = locale === "zh-CN";

	if (isCn) {
		return `
【HarmoniQ 站内说明（请优先依此回答；细则以各页面全文为准）】

一、买含「赠送报告」的水晶／饰品后
- 付款成功后请登录账号，打开 [我的订单](${base}/orders)，点进该笔订单即可在订单详情里填写：性别、出生日期，以及每一种赠送报告各一道你想了解的问题（提交后通常不可再改，以页面提示为准）。
- 赠送报告类型常见为：财运、感情、事业、健康（下单时已择一或按商品规则选择）。

二、报告里大概有什么
- 依据你提交的生辰与自订问题，由真人顾问撰写，偏个人化命理／能量向度的文字分析（实际章节以交付为准），不是即时自动生成的短文。

三、报告何时收到（与 [报告介绍与购买说明](${base}/report-preview) 页「发货方式」一致）
- 提交完整出生等信息后：电子版目标 72 小时内发到注册邮箱；若选纸本，约 7 天内完成撰写、校对、印刷并寄出（个案或假期可能顺延）。
- 单独购买的命理报告（从报告预览页加入购物车）的运费、纸本加价与退款段落，以该页「退款政策」「发货方式」为准。

四、实体商品（水晶等）物流
- 运费、地区、到货时间以结账页与 [退换货政策](${base}/customer/returns)、[用户条款](${base}/customer/terms) 为准；出货进度请在 [我的订单](${base}/orders) 查看，请勿编造具体天数或金额。

五、退款与退换（摘要，摘自站内 [退换货政策](${base}/customer/returns) / [用户条款](${base}/customer/terms)；若用户要细节请其阅读全文）
- 定制命理报告：不适用一般「七天冷静期」退换；报告预览页另载付款后两小时内可免费取消全额退款（以该页为准）。用户条款亦载明定制报告退款多限于技术性情形等，不同页面侧重点不同，以对应页面全文为准。
- 一般可退实体商品：须符合「完整状态」、未使用未拆封等；收货后 7 日内申请（个人原因退换的运费常由申请者承担）；退款处理约 7–14 个工作日退回原支付方式。瑕疵／错发请 7 日内联系客服并备妥照片与开箱视频。
- 报告个人资料填错：退换货页载明宜 24 小时内邮件联系客服更正，逾期可能无法处理。

六、联络
- 表单咨询可在 [联系我们](${base}/customer/contact) 留言；成功送出后站内提示约 24 小时内回复（以页面为准）。

【常用站内链接】[我的订单](${base}/orders) · [报告介绍与购买说明](${base}/report-preview) · [用户条款](${base}/customer/terms) · [退换货政策](${base}/customer/returns) · [联系我们](${base}/customer/contact) · [隐私政策](${base}/customer/privacy)
`.trim();
	}

	return `
【HarmoniQ 站內說明（請優先依此回答；細則以各頁面全文為準）】

一、買含「贈送報告」的水晶／飾品後
- 付款成功後請登入帳號，打開 [我的訂單](${base}/orders)，點進該筆訂單即可在訂單詳情裡填寫：性別、出生日期，以及每一種贈送報告各一道你想了解的問題（提交後通常不可再改，以頁面提示為準）。
- 贈送報告類型常見為：財運、感情、事業、健康（下單時已擇一或依商品規則選擇）。

二、報告裡大概有什麼
- 依你提交的生辰與自訂問題，由真人顧問撰寫，偏個人化命理／能量向度的文字分析（實際章節以交付為準），不是即時自動生成的小短文。

三、報告何時收到（與 [報告介紹與購買說明](${base}/report-preview) 頁「發貨方式」一致）
- 提交完整出生等資訊後：電子版目標 72 小時內寄到註冊信箱；若選紙本，約 7 日內完成撰寫、校對、印刷並寄出（個案或假期可能順延）。
- 單獨購買的命理報告（從報告預覽頁加入購物車）的運費、紙本加價與退款段落，以該頁「退款政策」「發貨方式」為準。

四、實體商品（水晶等）物流
- 運費、地區、到貨時間以結帳頁與 [退換貨政策](${base}/customer/returns)、[用戶條款](${base}/customer/terms) 為準；出貨進度請在 [我的訂單](${base}/orders) 查看，請勿編造具體天數或金額。

五、退款與退換（摘要，摘自站內 [退換貨政策](${base}/customer/returns) / [用戶條款](${base}/customer/terms)；若使用者要細節請其閱讀全文）
- 客製命理報告：不適用一般「七天冷靜期」退換；報告預覽頁另載付款後兩小時內可免費取消全額退款（以該頁為準）。用戶條款亦載明客製報告退款多限於技術性情形等，不同頁面側重不同，以對應頁面全文為準。
- 一般可退實體商品：須符合「完整狀態」、未使用未拆封等；收貨後 7 日內申請（個人原因退換的運費常由申請者負擔）；退款處理約 7–14 個工作天退回原支付方式。瑕疵／錯發請 7 日內聯絡客服並備妥照片與開箱影片。
- 報告個人資料填錯：退換貨頁載明宜 24 小時內以電郵聯絡客服更正，逾期可能無法處理。

六、聯絡
- 表單諮詢可在 [聯絡我們](${base}/customer/contact) 留言；成功送出後站內提示約 24 小時內回覆（以頁面為準）。

【常用站內連結】[我的訂單](${base}/orders) · [報告介紹與購買說明](${base}/report-preview) · [用戶條款](${base}/customer/terms) · [退換貨政策](${base}/customer/returns) · [聯絡我們](${base}/customer/contact) · [隱私政策](${base}/customer/privacy)
`.trim();
}
